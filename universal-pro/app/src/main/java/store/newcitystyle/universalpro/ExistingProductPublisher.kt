package store.newcitystyle.universalpro

import android.net.Uri
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.*
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyRow
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import coil.compose.AsyncImage
import kotlinx.coroutines.launch
import org.json.JSONObject

private val publishNavy=Color(0xFF0A2E73)
private val publishGold=Color(0xFFD4AF37)
private val publishGreen=Color(0xFF167A64)

@Composable
fun ExistingProductPublisher(
    session:NcsCloud.Session,
    product:JSONObject,
    onPublished:(JSONObject)->Unit
) {
    val ctx=LocalContext.current
    val scope=rememberCoroutineScope()
    var selectedPhotos by remember(product.optLong("id")){mutableStateOf<List<Uri>>(emptyList())}
    var uploaded by remember(product.optLong("id")){mutableStateOf<List<String>>(emptyList())}
    var generated by remember(product.optLong("id")){mutableStateOf<JSONObject?>(null)}
    var aiProvider by remember(product.optLong("id")){mutableStateOf("")}
    var busy by remember{mutableStateOf(false)}
    var message by remember{mutableStateOf("")}
    var failed by remember{mutableStateOf(false)}
    var approved by remember{mutableStateOf(false)}
    val picker=rememberLauncherForActivityResult(ActivityResultContracts.GetMultipleContents()){photos->
        selectedPhotos=photos.take(12);uploaded=emptyList();generated=null;approved=false;message=""
    }
    fun startAI() {
        if(selectedPhotos.isEmpty() || busy)return
        busy=true;message="Uploading "+selectedPhotos.size+" photos...";failed=false;approved=false
        scope.launch {
            try {
                val urls=mutableListOf<String>()
                for((index,photo) in selectedPhotos.withIndex()){
                    message="Uploading photo "+(index+1)+" / "+selectedPhotos.size
                    urls.add(ProductStudioWeb.uploadPhoto(ctx,photo,product.optLong("id")))
                    uploaded=urls.toList()
                }
                message="AI is generating product details..."
                val response=ProductStudioWeb.generate(urls.first(),product)
                generated=response.getJSONObject("details")
                aiProvider=response.optString("provider","AI")
                message="AI details ready for your review. Physical stock and MRP remain unchanged."
            }catch(e:Exception){
                failed=true;message=e.message?:"Upload/AI generation failed"
            }finally{busy=false}
        }
    }
    fun publish() {
        val details=generated?:return
        if(!approved||uploaded.isEmpty()||busy)return
        busy=true;message="Publishing to existing Web product...";failed=false
        scope.launch {
            try {
                val updated=ProductStudioWeb.publishExisting(session,product,uploaded,details)
                message="Published successfully to Web product #"+product.optLong("id")
                approved=false
                onPublished(updated)
            }catch(e:Exception){
                failed=true;message=e.message?:"Could not publish. Nothing else was changed."
            }finally{busy=false}
        }
    }

    Card(
        colors=CardDefaults.cardColors(containerColor=Color.White),
        shape=RoundedCornerShape(19.dp),
        modifier=Modifier.fillMaxWidth()
    ) {
        Column(Modifier.fillMaxWidth().padding(15.dp),verticalArrangement=Arrangement.spacedBy(11.dp)) {
            Text("PHOTO → AI → WEB PUBLISH",fontSize=13.sp,color=publishNavy,fontWeight=FontWeight.Black)
            Text("Update this existing product • no duplicate barcode, physical stock or new purchase entry",color=publishGreen,fontSize=11.sp)
            Button(
                enabled=!busy,
                onClick={picker.launch("image/*")},
                modifier=Modifier.fillMaxWidth(),
                colors=ButtonDefaults.buttonColors(containerColor=publishNavy)
            ){
                Icon(Icons.Default.AddPhotoAlternate,null)
                Spacer(Modifier.width(8.dp))
                Text("SELECT ONE OR MULTIPLE PHOTOS")
            }
            if(selectedPhotos.isNotEmpty()){
                Text(selectedPhotos.size.toString()+" new photos selected",color=publishNavy,fontWeight=FontWeight.Bold,fontSize=12.sp)
                LazyRow(horizontalArrangement=Arrangement.spacedBy(8.dp)){
                    items(selectedPhotos){photo->
                        Card(shape=RoundedCornerShape(12.dp),modifier=Modifier.size(93.dp)){
                            AsyncImage(model=photo,contentDescription="New design photo",modifier=Modifier.fillMaxSize())
                        }
                    }
                }
            }
            Button(
                enabled=selectedPhotos.isNotEmpty()&&!busy,
                onClick={startAI},modifier=Modifier.fillMaxWidth(),
                colors=ButtonDefaults.buttonColors(containerColor=Color(0xFF204F9A))
            ){
                Icon(Icons.Default.AutoAwesome,null)
                Spacer(Modifier.width(8.dp))
                Text("UPLOAD & GENERATE ALL AI DETAILS")
            }
            if(busy) LinearProgressIndicator(modifier=Modifier.fillMaxWidth())
            if(message.isNotBlank()) Text(message,color=if(failed)Color(0xFFB74045) else publishGreen,fontSize=11.sp)
            if(generated!=null){
                val g=generated!!
                Divider()
                Text("AI ENGINE: "+aiProvider.uppercase(),color=publishGreen,fontSize=10.sp,fontWeight=FontWeight.Bold)
                Text(g.optString("productName"),color=publishNavy,fontWeight=FontWeight.Black,fontSize=19.sp)
                Text(g.optString("description"),color=Color(0xFF405068),fontSize=12.sp,maxLines=8)
                Text("SEO: "+g.optString("seoTitle"),color=publishNavy,fontSize=11.sp,fontWeight=FontWeight.Bold)
                Text("FAQ",color=publishNavy,fontWeight=FontWeight.Black,fontSize=12.sp)
                val faqs=g.optJSONArray("faqs")
                if(faqs!=null) for(i in 0 until faqs.length()){
                    val x=faqs.optJSONObject(i)?:continue
                    Text(x.optString("question")+"\n"+x.optString("answer"),color=Color(0xFF405068),fontSize=11.sp)
                }
                Surface(color=Color(0xFFFFF8E4),shape=RoundedCornerShape(12.dp)){
                    Text("Online description, images, SEO and FAQ will update this existing product. Price, barcode, physical stock, variants and purchase values are preserved.",
                        Modifier.padding(11.dp),color=publishNavy,fontSize=11.sp)
                }
                Row(verticalAlignment=Alignment.CenterVertically){
                    Checkbox(checked=approved,onCheckedChange={approved=it})
                    Text("I reviewed these AI details and approve publication",fontSize=11.sp,color=publishNavy)
                }
                Button(
                    enabled=approved&&!busy,modifier=Modifier.fillMaxWidth(),onClick={publish},
                    colors=ButtonDefaults.buttonColors(containerColor=publishGreen)
                ){
                    Icon(Icons.Default.Publish,null)
                    Spacer(Modifier.width(8.dp))
                    Text("SAVE & PUBLISH THIS PRODUCT")
                }
            }
        }
    }
}
